// Set vs legendary-only vs hybrid parity report (docs/rework/depth/FOUNDATION.md §8). Actual 20 Hz simulation.
//   DATA_DIR=<fresh empty dir> BACKUP_DIR= BACKUP_KEEP=0 npx tsx scripts/audit-parity.ts [--only=<set,...>]
//   ... scripts/audit-parity.ts --kits=<kits.json>   play arbitrary KitSpec[] (server/test/parity/harness.ts) instead
// Writes docs/rework/depth/PARITY-MODEL.json and docs/rework/depth/PARITY.md (or, with --kits, prints the results).
// Nothing is persisted (no saves).
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { LEGENDARIES, SETS } from '../shared/src/data/items';
import { SKILLS } from '../shared/src/data/skills';
import {
  ENCOUNTER_CAP_MS, HYBRID_TOLERANCE, PARITY_DIFFICULTY, PARITY_WINDOW, SEEDS, measureProfile, parityProfiles, parityReadySkills, runKit,
  type KitSpec,
} from '../server/test/parity/harness';

assert.ok(process.env.DATA_DIR, 'Parity audit requires an isolated DATA_DIR');
const arg = (k: string) => process.argv.find((a) => a.startsWith(`--${k}=`))?.slice(k.length + 3);
const started = performance.now();
const s = (ms: number) => (ms / 1000).toFixed(1);

const kitsFile = arg('kits');
if (kitsFile) {
  const specs = JSON.parse(await fs.readFile(kitsFile, 'utf8')) as KitSpec[];
  const out = specs.map((spec) => { const r = runKit(spec); return { id: spec.id, mainSkills: spec.mainSkills, estTotalS: +s(r.estTotalMs), timeouts: r.timeouts }; });
  console.log(JSON.stringify(out, null, 2));
  process.exit(0);
}

const only = arg('only')?.split(',');
const rows = parityProfiles().filter((p) => !only || only.includes(p.set)).map((p) => measureProfile(p));
const ready = new Set(parityReadySkills());
const describe = (k: KitSpec) => {
  const sets = Object.values(k.equipment).filter((x) => x && 'set' in x).length;
  const legs = Object.entries(k.equipment).flatMap(([slot, x]) => (x && 'legendary' in x ? [`${slot}: ${LEGENDARIES[x.legendary].name}`] : []));
  return [sets ? `${sets} set` : null, ...legs, k.cube.some(Boolean) ? `Cube: ${k.cube.filter(Boolean).map((id) => LEGENDARIES[id!].name).join(', ')}` : null].filter(Boolean).join('; ');
};
const model = {
  generated: new Date().toISOString().slice(0, 10),
  scope: `Level 70, ${['Normal', 'Hard', 'Expert', 'Master', 'Torment I', 'Torment II'][PARITY_DIFFICULTY]}, actual 20 Hz, 3 encounters × ${SEEDS.length} seeds per kit, infinite player HP, deterministic chase; mean-roll non-Ancient items, 48 tier points, no runes/gems/upgrades/Paragon; ${ENCOUNTER_CAP_MS / 1000} s cap per encounter (timeouts are extrapolated from damage dealt and labelled).`,
  window: PARITY_WINDOW, hybridTolerance: HYBRID_TOLERANCE, parityReady: [...ready],
  rows: rows.map((r) => ({ set: r.profile.set, classId: r.profile.classId, skills: r.profile.skills, slots: r.profile.slots, ratio: r.ratio, hybridBetween: r.hybridBetween, passes: r.passes,
    enforced: r.profile.skills.some((id) => ready.has(id)),
    kits: Object.fromEntries(Object.entries(r.kits).map(([k, v]) => [k, { totalMs: v.totalMs, estTotalMs: v.estTotalMs, timeouts: v.timeouts, spec: v.spec, rows: v.rows }])) })),
};
await fs.mkdir('docs/rework/depth', { recursive: true });
await fs.writeFile('docs/rework/depth/PARITY-MODEL.json', JSON.stringify(model, null, 2) + '\n');
const md = [
  '# Parity report: set kit vs legendary-only kit vs hybrid',
  '',
  `Generated by \`scripts/audit-parity.ts\` (${model.generated}). ${model.scope}`,
  '',
  `Rule (plan §3.1): legendary-only clear time ≤ ${PARITY_WINDOW} × set clear time, hybrid between them (±${HYBRID_TOLERANCE * 100} %). Enforced in \`npm run verify\` only for skills flagged \`parityReady\` (today: ${ready.size ? [...ready].join(', ') : 'none'}).`,
  'Times are totals over all encounters; `~` marks totals that include extrapolated timeouts (cap × life / damage dealt) — measured where cleared, estimated otherwise. Kits are data (`spec` in PARITY-MODEL.json) and can be replayed with `--kits=<file>`.',
  '',
  '| Set | Class | Set-backed skills | Set kit | Hybrid | Legendary-only | Legendary / set | Hybrid between | 1.25 rule | Enforced |',
  '|---|---|---|---:|---:|---:|---:|---|---|---|',
  ...rows.map((r) => {
    const t = (k: 'set' | 'hybrid' | 'legendary') => `${r.kits[k].timeouts ? '~' : ''}${s(r.kits[k].estTotalMs)} s${r.kits[k].timeouts ? ` (${r.kits[k].timeouts} t/o)` : ''}`;
    return `| ${SETS[r.profile.set].name} | ${r.profile.classId} | ${r.profile.skills.map((id) => SKILLS[id].name).join(', ')} | ${t('set')} | ${t('hybrid')} | ${t('legendary')} | ${r.ratio.toFixed(2)} | ${r.hybridBetween ? 'yes' : 'no'} | ${r.passes ? 'pass' : 'fail'} | ${r.profile.skills.some((id) => ready.has(id)) ? 'yes' : 'no'} |`;
  }),
  '',
  '## Kits',
  '',
  ...rows.flatMap((r) => [`**${SETS[r.profile.set].name}** (loadout: ${r.profile.slots.map((id) => SKILLS[id].name).join(', ')})`, '',
    ...(['set', 'hybrid', 'legendary'] as const).map((k) => `- ${k}: ${describe(r.kits[k].spec)}`), '']),
];
await fs.writeFile('docs/rework/depth/PARITY.md', md.join('\n') + '\n');
console.log(JSON.stringify(rows.map((r) => ({ set: r.profile.set, set_s: +s(r.kits.set.estTotalMs), hybrid_s: +s(r.kits.hybrid.estTotalMs), legendary_s: +s(r.kits.legendary.estTotalMs), ratio: +r.ratio.toFixed(2), passes: r.passes }))));
console.log(`parity audit: ${rows.length} sets in ${((performance.now() - started) / 1000).toFixed(1)} s`);
