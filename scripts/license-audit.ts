// Whole-tree licence audit (F-PLT-08): every package the lockfile installs on this machine — production AND build/dev
// tools — with its declared licence, whether a licence file ships with it, and whether it runs in a shipped artifact.
// Reads only installed files (no network). Fails on a licence outside the allowed set, or a missing declaration.
//
//   npx tsx scripts/license-audit.ts              print the summary
//   npx tsx scripts/license-audit.ts --write      also write docs/licenses/FULL-TREE.md

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
/** Permissive licences that only ask for notice preservation; SIL OFL for fonts. Anything else needs a human review. */
const ALLOWED = new Set(['MIT', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', 'Apache-2.0', '0BSD', 'BlueOak-1.0.0', 'CC0-1.0', 'Unlicense', 'OFL-1.1', 'Python-2.0', 'CC-BY-4.0', 'MIT-0']);
/** Dev packages that still run in a shipped artifact: the server is started with tsx (npm start), which uses esbuild. */
const RUNTIME_DEV = new Set(['tsx', 'esbuild', 'get-tsconfig', 'resolve-pkg-maps']);
/** File-level copyleft is acceptable for tools that only transform our files at build time and are never distributed
 *  (MPL-2.0 obligations attach to distributing the MPL files themselves, e.g. lightningcss inside Vite). */
const BUILD_ONLY_ALLOWED = new Set(['MPL-2.0']);
const runsWithServer = (name: string) => RUNTIME_DEV.has(name) || name.startsWith('@esbuild/');

interface Row { location: string; name: string; version: string; license: string; dev: boolean; optional: boolean; licenseFile: boolean; shipped: string; ok: boolean }

function licenseOf(pkg: Record<string, unknown>): string {
  const l = pkg.license ?? pkg.licenses;
  if (typeof l === 'string') return l;
  if (Array.isArray(l)) return l.map(x => (x as { type?: string }).type ?? '?').join(' OR ');
  if (l && typeof l === 'object') return (l as { type?: string }).type ?? '?';
  return '';
}
function allowed(expr: string): boolean {
  if (!expr) return false;
  const parts = expr.replace(/[()]/g, '').split(/\s+(?:OR|AND)\s+/);
  return /\bOR\b/.test(expr) ? parts.some(p => ALLOWED.has(p.trim())) : parts.every(p => ALLOWED.has(p.trim()));
}

export function auditTree(): Row[] {
  const lock = JSON.parse(fs.readFileSync(path.join(root, 'package-lock.json'), 'utf8')) as { packages: Record<string, { dev?: boolean; optional?: boolean; devOptional?: boolean }> };
  const rows: Row[] = [];
  for (const [location, entry] of Object.entries(lock.packages)) {
    if (!location) continue;
    const dir = path.join(root, location), manifest = path.join(dir, 'package.json');
    if (!fs.existsSync(manifest)) continue; // optional platform package not installed on this machine
    const pkg = JSON.parse(fs.readFileSync(manifest, 'utf8')) as Record<string, unknown>;
    const license = licenseOf(pkg);
    const files = fs.readdirSync(dir);
    const name = String(pkg.name ?? location.replace(/^.*node_modules\//, ''));
    const dev = !!(entry.dev || entry.devOptional);
    rows.push({
      location, name, version: String(pkg.version ?? '?'), license, dev, optional: !!entry.optional,
      licenseFile: files.some(f => /^(licen[cs]e|copying)/i.test(f)),
      shipped: !dev ? 'game (client bundle and/or server)' : runsWithServer(name) ? 'server runtime (npm start uses tsx)' : 'build/test tool only',
      ok: allowed(license) || (dev && !runsWithServer(name) && BUILD_ONLY_ALLOWED.has(license)),
    });
  }
  return rows.sort((a, b) => a.name.localeCompare(b.name));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const rows = auditTree();
  const by = new Map<string, number>();
  for (const r of rows) by.set(r.license || '(none)', (by.get(r.license || '(none)') ?? 0) + 1);
  const bad = rows.filter(r => !r.ok), noFile = rows.filter(r => !r.licenseFile);
  console.log(`${rows.length} installed packages: ${[...by].sort((a, b) => b[1] - a[1]).map(([l, n]) => `${l} ${n}`).join(', ')}`);
  console.log(`${rows.filter(r => !r.dev).length} production, ${rows.filter(r => r.dev).length} dev (${rows.filter(r => r.dev && r.shipped.startsWith('server')).length} of them run with the server)`);
  console.log(`${noFile.length} without a licence file: ${noFile.map(r => r.name).join(', ') || '-'}`);
  if (process.argv.includes('--write')) {
    const lines = ['# Installed dependency tree — licence audit', '',
      `Generated by \`npx tsx scripts/license-audit.ts --write\` from installed \`node_modules\` metadata (no network), ${new Date().toISOString().slice(0, 10)}.`,
      'Production packages were reviewed byte-for-byte by Codex (README.md, installed-production.json); this table adds every build/test tool and marks which dev packages still run in a shipped server (`npm start` = `tsx`).',
      'A declared licence is metadata, not proof; packages without a licence file are listed for follow-up.', '',
      `Totals: ${rows.length} packages — ${[...by].sort((a, b) => b[1] - a[1]).map(([l, n]) => `${l} ${n}`).join(', ')}. Outside the allowed set: ${bad.length}.`, '',
      '| Package | Version | Licence | Licence file | Runs where |', '|---|---|---|---|---|',
      ...rows.map(r => `| ${r.name} | ${r.version} | ${r.license || '**none declared**'}${r.ok ? '' : ' ⚠'} | ${r.licenseFile ? 'yes' : '**no**'} | ${r.shipped} |`), ''];
    fs.writeFileSync(path.join(root, 'docs/licenses/FULL-TREE.md'), lines.join('\n'));
    console.log('wrote docs/licenses/FULL-TREE.md');
  }
  if (bad.length) { console.error(`Outside the allowed licence set (needs review): ${bad.map(r => `${r.name}@${r.version} (${r.license || 'none'})`).join(', ')}`); process.exitCode = 1; }
}
